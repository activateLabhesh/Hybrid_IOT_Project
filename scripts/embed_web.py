"""Gzip the files in web/ and embed them into src/web_assets.h.

Runs automatically as a PlatformIO pre-build script. Can also be run by hand:
    python3 scripts/embed_web.py
"""
import gzip
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB_DIR = os.path.join(PROJECT_DIR, "web")
OUT = os.path.join(PROJECT_DIR, "src", "web_assets.h")

FILES = [
    ("/", "index.html", "text/html"),
    ("/app.js", "app.js", "application/javascript"),
    ("/style.css", "style.css", "text/css"),
]


def ident(name):
    return "WEB_" + "".join(c.upper() if c.isalnum() else "_" for c in name)


def main():
    lines = [
        "// AUTO-GENERATED by scripts/embed_web.py — do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
    ]
    table = []
    for route, fname, mime in FILES:
        with open(os.path.join(WEB_DIR, fname), "rb") as f:
            data = gzip.compress(f.read(), compresslevel=9, mtime=0)
        name = ident(fname)
        body = ",".join(str(b) for b in data)
        lines.append(f"static const uint8_t {name}[] PROGMEM = {{{body}}};")
        table.append(f'  {{"{route}", "{mime}", {name}, sizeof({name})}},')

    lines += [
        "",
        "struct WebAsset { const char* path; const char* mime; const uint8_t* data; size_t len; };",
        "static const WebAsset WEB_ASSETS[] = {",
        *table,
        "};",
        "static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);",
        "",
    ]
    content = "\n".join(lines)
    old = open(OUT).read() if os.path.exists(OUT) else None
    if content != old:
        with open(OUT, "w") as f:
            f.write(content)
        print("embed_web: regenerated src/web_assets.h")


main()
